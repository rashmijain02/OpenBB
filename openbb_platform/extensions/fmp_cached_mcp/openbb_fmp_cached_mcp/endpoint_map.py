"""Hosted tool → endpoint → FMP REST mapping (#1299).

``assets/endpoint_map.json`` is generated by ``scripts/fmp_mcp_build_assets.py``
from the recorded hosted fixtures; ``assets/tools.json`` is the recorded hosted
``tools/list`` served verbatim.
"""

from __future__ import annotations

import json
from functools import lru_cache
from importlib import resources
from typing import Any

#: Retention classes (plan §4.2). Only ``ephemeral`` (and feed listings) expire.
RETENTION_CLASSES = frozenset(
    {
        "series",
        "immutable-doc",
        "revisable",
        "reference",
        "feed",
        "ephemeral",
        "no-store",
    }
)

#: Hosted argument names that FMP REST spells differently.
PARAM_RENAMES = {"from_date": "from", "to_date": "to"}


def _asset(name: str) -> Any:
    text = (
        resources.files("openbb_fmp_cached_mcp.assets")
        .joinpath(name)
        .read_text(encoding="utf-8")
    )
    return json.loads(text)


@lru_cache(maxsize=1)
def load_tools() -> list[dict[str, Any]]:
    """Return the hosted ``tools/list`` entries, in hosted order."""
    return _asset("tools.json")


@lru_cache(maxsize=1)
def load_endpoint_map() -> dict[str, dict[str, dict[str, Any]]]:
    """Return ``{tool: {endpoint: {path, required, retention, [defaults]}}}``."""
    return _asset("endpoint_map.json")


def endpoint_spec(tool: str, endpoint: str) -> dict[str, Any]:
    """Return the map entry for ``tool``/``endpoint`` (``KeyError`` if unknown)."""
    return load_endpoint_map()[tool][endpoint]


#: Hosted endpoints whose data the ``fmp_cached`` provider knows under an
#: OpenBB model name in ``openbb_fmp_cached.utils.plan_limited`` (CLAUDE.md
#: FMP-tier rule). Live tests for these carry the ``plan_limited`` marker when
#: the registry lists them.
PLAN_LIMITED_ALIASES: dict[str, str] = {
    "marketPerformance/most-active": "EquityActive",
    "crypto/cryptocurrency-list": "CryptoSearch",
    "indexes/sp-500": "IndexConstituents",
    "indexes/nasdaq": "IndexConstituents",
    "indexes/dow-jones": "IndexConstituents",
}


def plan_limited_model(tool: str, endpoint: str) -> str | None:
    """OpenBB model name to look up in the ``plan_limited`` registry, if any."""
    return PLAN_LIMITED_ALIASES.get(f"{tool}/{endpoint}")
